// Writes lib/geo/world-land.ts: the world's land outline as one SVG path, from Natural
// Earth's 1:110m data (public domain, via the world-atlas package). Run after changing the
// projection in lib/geo/projection.ts:  node scripts/build-world-map.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topology = JSON.parse(
  readFileSync(require.resolve("world-atlas/land-110m.json"), "utf8"),
);
const land = feature(topology, topology.objects.land);

// Keep in step with lib/geo/projection.ts.
const WIDTH = 1000;
const NORTH = 84;
const SOUTH = -58;
const HEIGHT = Math.round((WIDTH * (NORTH - SOUTH)) / 360);
const x = (lon) => ((lon + 180) / 360) * WIDTH;
const y = (lat) => ((NORTH - lat) / (NORTH - SOUTH)) * HEIGHT;
const r = (n) => Math.round(n * 10) / 10;

const rings = [];
for (const geometry of land.features.map((f) => f.geometry)) {
  const polygons =
    geometry.type === "Polygon" ? [geometry.coordinates] : geometry.coordinates;
  for (const polygon of polygons) {
    for (const ring of polygon) {
      // Antarctica sits below the crop and only adds a band along the bottom.
      if (ring.every(([, lat]) => lat < SOUTH)) continue;
      // A ring that crosses the antimeridian (eastern Russia, Fiji) would otherwise draw a
      // line straight across the map; start a new subpath at each crossing instead.
      let previous = "";
      let previousLon = null;
      let broken = false;
      let d = "";
      let count = 0;
      for (const [lon, lat] of ring) {
        const point = `${r(x(lon))},${r(y(Math.max(SOUTH, lat)))}`;
        if (point === previous) continue;
        const jump = previousLon !== null && Math.abs(lon - previousLon) > 180;
        if (jump) broken = true;
        d += `${count === 0 || jump ? "M" : "L"}${point}`;
        previous = point;
        previousLon = lon;
        count++;
      }
      if (count > 2) rings.push(broken ? d : `${d}Z`);
    }
  }
}

writeFileSync(
  new URL("../lib/geo/world-land.ts", import.meta.url),
  `// Generated by scripts/build-world-map.mjs from Natural Earth 1:110m land (public domain).
// Do not edit by hand.
export const WORLD_LAND_PATH =
  ${JSON.stringify(rings.join(""))};
`,
);
console.log(`world-land.ts: ${rings.length} rings, ${WIDTH}x${HEIGHT}`);
